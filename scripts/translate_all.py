def plural_to_singular(word):
    """Convierte plurales irregulares a singular para buscar en diccionario."""
    irregulars = {
        "elves": "elf",
        "elves'": "elf",
        "dwarves": "dwarf",
        "dwarves'": "dwarf",
        "wolves": "wolf",
        "wolves'": "wolf",
        "wurms": "wurm",
        "wurms'": "wurm",
        "staves": "staff",
        "feet": "foot",
        "teeth": "tooth",
        "men": "man",
        "women": "woman",
        "children": "child",
        "lives": "life",
        "halves": "half",
    }
    # Primero ver irregulares
    lower = word.lower()
    if lower in irregulars:
        return irregulars[lower]
    # Plural regular: quitar 's' o 'es'
    if lower.endswith("es") and len(lower) > 4:
        return word[:-2]
    if lower.endswith("s") and not lower.endswith("ss") and len(lower) > 3:
        return word[:-1]
    if lower.endswith("ies") and len(lower) > 4:
        return word[:-3] + "y"
    return word


