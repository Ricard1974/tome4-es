def translate_text(text):
    """Traduce un texto usando diccionarios y reglas."""
    if not text or text.strip() == "":
        return text

    # 1. Buscar en frases completas
    if text in PHRASES:
        return PHRASES[text]

    # 2. No traducir si tiene códigos de color (#...) o es solo eso
    if re.match(r"^#[A-Z_]+\s*#", text):
        return text

    # 3. No traducir nombres propios conocidos
    proper_names = {
        "Maj'Eyal",
        "Eyal",
        "Sher'Tul",
        "Amakthel",
        "Elandar",
        "Aeryn",
        "Celestene",
        "Linaniil",
        "Urkis",
        "Shasshhiy'Kaish",
        "Cthulhu",
        "Voratun",
        "Stralite",
        "Mithril",
        "Kerr'Bak",
        "Tannen",
    }
    if text in proper_names:
        return text

    # 4. Traducir palabra por palabra
    words = text.split(" ")
    translated_words = []
    for word in words:
        # Mantener puntuación
        stripped = word.strip(",.!?;:()[]{}'\"")
        punct_start = word[: len(word) - len(word.lstrip(",.!?;:()[]{}'\""))]
        punct_end = word[len(word.rstrip(",.!?;:()[]{}'\"")) :]

        # Inicializar trans
        trans = stripped

        # Buscar en frases completas (versión lowercase)
        if stripped.lower() in {k.lower() for k in PHRASES}:
            # Encontrar la key correcta
            for key, val in PHRASES.items():
                if key.lower() == stripped.lower():
                    trans = val
                    break
        # Buscar en diccionario EN-ES
        elif stripped.lower() in EN_ES:
            trans = EN_ES[stripped.lower()]
        elif stripped.lower().rstrip("s") in EN_ES:
            trans = EN_ES[stripped.lower().rstrip("s")]

        # Preservar capitalización
        if stripped and stripped[0].isupper() and trans:
            trans = trans[0].upper() + trans[1:] if len(trans) > 1 else trans.upper()

        translated_words.append(punct_start + trans + punct_end)

    result = " ".join(translated_words)

    # 5. Correcciones post-traducción
    # Artículos
    result = re.sub(r"\bEl (\w+) de\b", r"el \1 de", result)
    result = re.sub(r"^El ", r"el ", result)

    return result


def translate_file(fpath):
    """Traduce todas las cadenas de un archivo."""
    with open(fpath, "r", encoding="utf-8") as f:
        content = f.read()

    count = 0
    lines = content.split("\n")
    new_lines = []

    for line in lines:
        # Buscar t("original", "original|trans", "type")
        match = re.match(
            r'^(\s*)t\("((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)',
            line,
        )
        if match:
            indent = match.group(1)
            original = match.group(2)
            current_trans = match.group(3)
            type_ = match.group(4)

            # Solo traducir si original == current (aún sin traducir)
            if original != current_trans:
                new_lines.append(line)
                continue

            # Detectar placeholders y códigos de color
            has_color = bool(re.search(r"#[A-Z_]+", original))
            has_format = bool(re.search(r"%[sd]", original))

            translation = translate_text(original)

            # Si la traducción es igual al original, forzar capitalización
            if translation == original or not translation:
                translation = original
            else:
                count += 1

            safe_translation = translation.replace('"', '\\"')
            new_line = f'{indent}t("{original}", "{safe_translation}", "{type_}")'
            new_lines.append(new_line)
        else:
            new_lines.append(line)

    new_content = "\n".join(new_lines)
    with open(fpath, "w", encoding="utf-8") as f:
        f.write(new_content)

    return count


